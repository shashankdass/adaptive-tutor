def add_xp(amount):
    st.session_state.xp += amount
    new_level = 1 + st.session_state.xp // XP_PER_LEVEL
    if new_level > st.session_state.level:
        st.session_state.level = new_level
        st.session_state.just_leveled = True


def check_badges():
    s = st.session_state
    rules = [
        ("🎯 First Steps", s.xp > 0),
        ("🔥 On Fire", s.streak >= 3),
        ("⚡ Unstoppable", s.streak >= 5),
        ("🌟 Rising Star", s.level >= 2),
        ("👑 Scholar", s.level >= 5),
        ("🧠 Prodigy", s.baseline_skill == "Expert"),
        ("📘 Chapter Master", s.chapters_completed >= 1),
    ]
    newly = []
    for title, cond in rules:
        if cond and title not in s.badges:
            s.badges.append(title)
            newly.append(title)
    return newly


def _promote():
    chapters = chapters_for(st.session_state.selected_subject)
    tier_idx = TIERS.index(st.session_state.current_difficulty)
    if tier_idx < len(TIERS) - 1:
        st.session_state.current_difficulty = TIERS[tier_idx + 1]
        return f"🎉 Promoted to **{st.session_state.current_difficulty}** tier!"
    chap_idx = chapters.index(st.session_state.current_chapter)
    st.session_state.chapters_completed += 1
    if chap_idx < len(chapters) - 1:
        st.session_state.current_chapter = chapters[chap_idx + 1]
        st.session_state.current_difficulty = "Novice"
        return f"🏆 Chapter cleared! Advancing to **{st.session_state.current_chapter}**."
    st.session_state.completed = True
    return "🎓 Subject mastered — all chapters complete!"


def _demote():
    tier_idx = TIERS.index(st.session_state.current_difficulty)
    if tier_idx > 0:
        st.session_state.current_difficulty = TIERS[tier_idx - 1]
        return f"↩️ Difficulty eased to **{st.session_state.current_difficulty}** — reinforce the basics."
    return "💪 Holding at Novice — let's build a solid base."


def record_correct():
    add_xp(XP_CORRECT)
    st.session_state.streak += 1
    st.session_state.consecutive_correct += 1
    if st.session_state.consecutive_correct >= PROMOTION_THRESHOLD:
        st.session_state.consecutive_correct = 0
        return _promote()
    remaining = PROMOTION_THRESHOLD - st.session_state.consecutive_correct
    return f"✅ Correct! +{XP_CORRECT} XP · {remaining} more to advance."


def record_wrong():
    st.session_state.streak = 0
    st.session_state.consecutive_correct = 0
    return _demote()


def next_locked_chapter():
    """First locked chapter in the active subject (for the recommendation engine)."""
    subject = st.session_state.selected_subject
    if not subject:
        return None
    for ch in chapters_for(subject):
        if module_key(subject, ch) not in st.session_state.parent_approved_modules:
            return ch
    return None


def has_milestone():
    s = st.session_state
    return s.chapters_completed > 0 or s.level >= 2 or s.streak >= PROMOTION_THRESHOLD


