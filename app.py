# Phase: STUDY
# =========================================================================== #
def phase_study():
    s = st.session_state
    if s.completed:
        return phase_complete()

    st.title("📖 STUDY MODE")
    st.caption(f"{s.selected_subject} · {s.current_chapter} · **{s.current_difficulty}**")
    if s.baseline_skill:
        st.markdown(f"Diagnostic locked your baseline at **{s.baseline_skill}**. 🧠")

    if s.study_content is None:
        with st.spinner("Compiling your custom briefing…"):
            try:
                s.study_content = generate_study_material(
                    s.selected_subject, s.current_chapter, s.current_difficulty
                )
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return

    with st.container(border=True):
        st.markdown(s.study_content)

    col1, col2 = st.columns(2)
    with col1:
        if not s.study_read:
            if st.button(f"📗 Read Material (+{XP_READ} XP)", type="primary",
                         use_container_width=True):
                add_xp(XP_READ)
                s.study_read = True
                st.rerun()
        else:
            st.success(f"✓ +{XP_READ} XP claimed")
    with col2:
        if s.study_read and st.button("⚔️ Take the Quiz →", type="primary",
                                      use_container_width=True):
            s.phase = "QUIZ"
            s.quiz_question = None
            s.quiz_result = None
            st.rerun()

    celebrate_levelups()


