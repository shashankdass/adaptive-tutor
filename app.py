def add_xp(amount):
    stats = st.session_state.student_stats
    stats["xp"] += amount
    new_level = 1 + stats["xp"] // XP_PER_LEVEL
    if new_level > stats["level"]:
        stats["level"] = new_level
        st.session_state.just_leveled = True


def completed_module_names():
    return {key.split(" :: ")[-1] for key in st.session_state.completed_modules}


def completed_in_track(track):
    return any(key.startswith(track + " :: ") for key in st.session_state.completed_modules)


def check_badges():
    s = st.session_state
    stats = s.student_stats
    done = completed_module_names()
    rules = [
        ("🎯 First Quest", stats["xp"] > 0),
        ("🔥 Streak Star", stats["streak"] >= 3),
        ("⚡ Puzzle Champ", stats["streak"] >= 5),
        ("🌟 Rising Star", stats["level"] >= 2),
        ("🧙 Logic Wizard", completed_in_track(LOGIC)),
        ("🔁 Loop Master", "Loop Patterns" in done),
        ("🤖 Robot Boss", "Robot Commands" in done),
        ("🚀 Game Builder", "Text-Adventure Game Building" in done),
        ("🧠 Brainiac", s.baseline_skill == "Expert"),
    ]
    newly = []
    for title, cond in rules:
        if cond and title not in s.badges:
            s.badges.append(title)
            newly.append(title)
    return newly


def _record_accuracy(correct):
    key = module_key(st.session_state.current_subject, st.session_state.current_chapter)
    bucket = st.session_state.skill_gaps.setdefault(key, {"correct": 0, "total": 0})
    bucket["total"] += 1
    if correct:
        bucket["correct"] += 1


def _advance_or_complete():
    s = st.session_state
    idx = TIERS.index(s.current_difficulty)
    if idx < len(TIERS) - 1:
        s.current_difficulty = TIERS[idx + 1]
        return f"🎉 Level up! You're now a **{TIER_LABELS[s.current_difficulty]}**!"
    key = module_key(s.current_subject, s.current_chapter)
    if key not in s.completed_modules:
        s.completed_modules.append(key)
    s.module_complete = True
    return "🏆 Quest complete — you mastered this adventure!"


def _demote():
    # Gentle, safe self-adjust: never drops below the easiest tier, always kind.
    s = st.session_state
    idx = TIERS.index(s.current_difficulty)
    if idx > 0:
        s.current_difficulty = TIERS[idx - 1]
        return (f"💛 No worries! Let's warm up at **{TIER_LABELS[s.current_difficulty]}** "
                "and try again.")
    return "💪 Great try! We'll keep practicing here — you're getting stronger!"


def record_correct():
    s = st.session_state
    _record_accuracy(True)
    add_xp(XP_CORRECT)
    s.student_stats["streak"] += 1
    s.consecutive_correct += 1
    if s.consecutive_correct >= PROMOTION_THRESHOLD:
        s.consecutive_correct = 0
        return _advance_or_complete()
    remaining = PROMOTION_THRESHOLD - s.consecutive_correct
    return f"✅ Yes! +{XP_CORRECT} XP · {remaining} more win to level up!"


def record_wrong():
    s = st.session_state
    _record_accuracy(False)
    s.student_stats["streak"] = 0
    s.consecutive_correct = 0
    return _demote()


def growth_areas():
    """List of (module_key, accuracy) below threshold with enough attempts."""
    out = []
    for key, v in st.session_state.skill_gaps.items():
        if v["total"] >= GROW_MIN_ATTEMPTS:
            acc = v["correct"] / v["total"]
            if acc < GROW_THRESHOLD:
                out.append((key, acc))
    return out


# ---- Learner model: path evolution + mastery scoring ----
def update_live_path():
    """Recompute live_path from original_path based on mastery (idempotent).

    >80 → Acceleration (insert a Challenge Quest after the active node);
    <50 → Remediation (inject a Practice Quest before the next core node);
    50-80 → maintain the baseline blueprint unchanged.
    """
    s = st.session_state
    path = list(s.original_path)
    if not path:
        s.live_path = []
        return
    idx = min(s.path_index, len(path) - 1)
    if s.mastery_score > 80:
        path.insert(idx + 1, CHALLENGE_NODE)
        # Strong mastery also skips the next basic module entirely (Skip mode).
        if s.mastery_score >= 90 and idx + 2 < len(path):
            path.pop(idx + 2)
    elif s.mastery_score < 50:
        path.insert(min(idx + 1, len(path)), REMEDIATION_NODE)
    s.live_path = path


def apply_mastery(delta, why):
    """Adjust mastery (clamped 0-100), redraw the path, and log the reasoning."""
    s = st.session_state
    s.mastery_score = max(0, min(100, s.mastery_score + delta))
    update_live_path()
    sign = f"+{delta}" if delta > 0 else (str(delta) if delta < 0 else "±0")
    if s.mastery_score > 80:
        branch = "Acceleration unlocked — a Challenge Quest was inserted! ⚡"
    elif s.mastery_score < 50:
        branch = "Remediation branch unlocked to bridge the gap. 🛟"
    else:
        branch = "Course maintained — steady progress."
    s.mastery_reason = f"System Alert: Mastery {sign} ({why}). {branch}"


def advance_path_node():
    s = st.session_state
    s.path_index = min(s.path_index + 1, max(0, len(s.original_path) - 1))
    update_live_path()


def _breadcrumb(nodes, active_name):
    chips = []
    for n in nodes:
        if n.startswith(("⚡", "🛟")):
            cls = "node node-new"
        elif n == active_name:
            cls = "node node-active"
        else:
            cls = "node"
        chips.append(f'<span class="{cls}">{n}</span>')
    return '<div class="path-row">' + " ➔ ".join(chips) + "</div>"


def render_path_map():
    """The Path Evolution Map: original blueprint vs the live, mutating path."""
    s = st.session_state
    if not s.original_path:
        return
    active_name = s.original_path[min(s.path_index, len(s.original_path) - 1)]
    st.markdown("##### 🗺️ Path Evolution Map")
    col1, col2 = st.columns(2)
    with col1:
        st.markdown("**Originally Planned Path:**")
        st.markdown(_breadcrumb(s.original_path, active_name), unsafe_allow_html=True)
    with col2:
        st.markdown("**Updated Live Path:**")
        st.markdown(_breadcrumb(s.live_path, active_name), unsafe_allow_html=True)


