def _finalize_diagnostic():
    s = st.session_state
    correct = s.diag_correct
    baseline = "Novice" if correct <= 1 else "Intermediate" if correct == 2 else "Expert"
    s.baseline_skill = baseline
    s.current_difficulty = baseline
    s.phase = "STUDY"
    s.study_content = None
    s.study_read = False
    check_badges()


def phase_diagnostic():
    s = st.session_state
    st.title("🧪 WARM-UP CHALLENGE")
    st.caption(f"{s.current_chapter} · finding your starting level — just do your best! 💪")
    if s.diag_index >= NUM_DIAGNOSTIC:
        _finalize_diagnostic()
        st.rerun()
        return
    probe_tier = TIERS[s.diag_index]
    if s.diag_question is None:
        with st.spinner(f"Loading warm-up {s.diag_index + 1}/{NUM_DIAGNOSTIC}…"):
            try:
                s.diag_question = generate_quiz_question(s.current_subject, s.current_chapter, probe_tier)
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return
    q = s.diag_question
    st.progress(s.diag_index / NUM_DIAGNOSTIC, text=f"Warm-up {s.diag_index + 1} of {NUM_DIAGNOSTIC}")
    with st.container(border=True):
        st.markdown(f"**[{TIER_LABELS[probe_tier]}]** {q['question']}")
        choice = st.radio("Your answer:", list("ABCD"),
                          format_func=lambda k: f"{k}.  {q['options'][k]}",
                          index=None, key=f"diag_{s.diag_index}")
        if st.button("Submit ▶", type="primary"):
            if choice is None:
                st.warning("Pick an answer to keep going!")
            else:
                if choice == q["correct_option"]:
                    s.diag_correct += 1
                s.diag_index += 1
                s.diag_question = None
                st.rerun()


