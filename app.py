def phase_subject_selection():
    st.title("🕹️ ADAPTIVE TUTOR")
    st.markdown("#### Choose your skill tree, challenger.")
    st.caption("Each subject runs a quick diagnostic, then adapts to your level as you play.")
    st.write("")

    subjects = list(SUBJECTS.keys())
    cols = st.columns(2)
    for i, subject in enumerate(subjects):
        icon, blurb = SUBJECT_META.get(subject, ("📚", ""))
        with cols[i % 2]:
            st.markdown(
                f"""
                <div class="subject-card">
                  <div class="title">{icon} {subject}</div>
                  <div class="blurb">{blurb}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )
            if st.button(f"▶ Start {subject.split()[0]}", key=f"pick_{i}",
                         use_container_width=True):
                start_subject(subject)
                st.rerun()
            st.write("")


