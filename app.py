# Phase: COMPLETE
# =========================================================================== #
def phase_complete():
    s = st.session_state
    st.balloons()
    st.title("🎓 SUBJECT MASTERED")
    with st.container(border=True):
        st.markdown(f"### You conquered **{s.selected_subject}**!")
        st.markdown(
            f"- **Level:** {s.level}\n"
            f"- **Total XP:** {s.xp}\n"
            f"- **Badges:** {len(s.badges)}\n"
            f"- **Chapters cleared:** {s.chapters_completed}"
        )
    if st.button("🕹️ Pick another subject", type="primary"):
        back_to_selection()
        st.rerun()


