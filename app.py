def init_state():
    defaults = {
        "backend": resolve_backend(),
        "selected_subject": None,   # None => show landing page
        "current_chapter": None,    # set when a subject is chosen
        "current_difficulty": TIERS[0],
        "consecutive_correct": 0,
        "history": [],
        "current_question": None,
        "last_result": None,
        "answer_mode": "Multiple choice",
        "completed": False,
        "total_answered": 0,
        "total_correct": 0,
    }
    for key, value in defaults.items():
        st.session_state.setdefault(key, value)


def reset_progress():
    """Reset all per-run progress, keeping the currently selected subject."""
    subject = st.session_state.get("selected_subject")
    chapters = chapters_for(subject)
    st.session_state.current_chapter = chapters[0] if chapters else None
    st.session_state.current_difficulty = TIERS[0]
    st.session_state.consecutive_correct = 0
    st.session_state.history = []
    st.session_state.current_question = None
    st.session_state.last_result = None
    st.session_state.completed = False
    st.session_state.total_answered = 0
    st.session_state.total_correct = 0
    st.session_state.pop("open_answer", None)


def start_subject(subject):
    """Lock in a subject and initialise a fresh learning session for it."""
    st.session_state.selected_subject = subject
    reset_progress()  # picks up the new subject's first chapter


def change_subject():
    """Return to the landing page, clearing the current session."""
    st.session_state.selected_subject = None
    reset_progress()


# --------------------------------------------------------------------------- #
# Adaptivity logic
# --------------------------------------------------------------------------- #
def _promote():
    """Move up a tier; graduate to the next chapter (or finish) at the top."""
    chapters = chapters_for(st.session_state.selected_subject)
    tier_idx = TIERS.index(st.session_state.current_difficulty)
    if tier_idx < len(TIERS) - 1:
        st.session_state.current_difficulty = TIERS[tier_idx + 1]
        return f"🎉 Two in a row! Promoted to **{st.session_state.current_difficulty}** tier."

    chap_idx = chapters.index(st.session_state.current_chapter)
    if chap_idx < len(chapters) - 1:
        st.session_state.current_chapter = chapters[chap_idx + 1]
        st.session_state.current_difficulty = TIERS[0]
        return f"🏆 Chapter mastered! Advancing to **{st.session_state.current_chapter}** at Novice."

    st.session_state.completed = True
    return "🎓 You've mastered every chapter. Subject complete!"


def _demote():
    """Drop one tier to reinforce foundations (no-op at Novice)."""
    tier_idx = TIERS.index(st.session_state.current_difficulty)
    if tier_idx > 0:
        st.session_state.current_difficulty = TIERS[tier_idx - 1]
        return f"↩️ Let's reinforce the basics — back to **{st.session_state.current_difficulty}** tier."
    return "💪 Staying at Novice to build a solid foundation. Keep going!"


def apply_result(correct):
    """Update streak/difficulty/chapter based on a graded answer."""
    st.session_state.total_answered += 1
    if correct:
        st.session_state.total_correct += 1
        st.session_state.consecutive_correct += 1
        if st.session_state.consecutive_correct >= PROMOTION_THRESHOLD:
            st.session_state.consecutive_correct = 0
            return _promote()
        remaining = PROMOTION_THRESHOLD - st.session_state.consecutive_correct
        return f"✅ Correct! {remaining} more in a row to level up."
    st.session_state.consecutive_correct = 0
    return _demote()


def render_llm_error(exc):
    """Friendly error panel for connection / model problems."""
    backend = st.session_state.backend
    if backend["name"] == "groq":
        st.error(
            "**Couldn't reach the Groq API.** Check that:\n\n"
            "1. `GROQ_API_KEY` is set (Streamlit secret or env var).\n"
            f"2. The model `{backend['model']}` is valid and your key has quota.\n\n"
            f"Details: `{exc}`"
        )
    else:
        st.error(
            "**Couldn't reach the local model.** Check that everything is set up:"
            "\n\n1. Start the server:  `ollama serve`\n"
            f"2. Pull the model:  `ollama pull {backend['model']}`\n\n"
            f"Details: `{exc}`"
        )


