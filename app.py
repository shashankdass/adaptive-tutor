"""Adaptive Learning Tutor — an AI-driven adaptive learning app.

Flow:
    1. Subject-selection landing page.
    2. Once a subject is chosen, the adaptive quiz dashboard takes over, loading
       that subject's curriculum dynamically.

Questions are generated by a Llama 3 model; difficulty adapts to performance.

LLM backend (auto-detected):
    - Local dev → Ollama (`ollama serve` + `ollama pull llama3`).
    - Cloud     → Groq's free Llama 3 API. Set GROQ_API_KEY (Streamlit secret or
                  env var) and the app uses Groq automatically.

Run locally:
    streamlit run app.py
"""

