# Phase: QUIZ
# =========================================================================== #
def phase_quiz():
    s = st.session_state
    if s.completed:
        return phase_complete()

    st.title("⚔️ QUIZ ARENA")
    st.caption(f"{s.selected_subject} · {s.current_chapter} · **{s.current_difficulty}**")

    if s.quiz_question is None:
        with st.spinner("Summoning a challenge…"):
            try:
                s.quiz_question = generate_mcq(
                    s.selected_subject, s.current_chapter, s.current_difficulty
                )
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return

    q = s.quiz_question

    # Phase 1: awaiting answer.
    if s.quiz_result is None:
        with st.container(border=True):
            st.markdown(f"### {q['question']}")
            choice = st.radio(
                "Lock in your answer:", list("ABCD"),
                format_func=lambda k: f"{k}.  {q['options'][k]}",
                index=None, key="quiz_choice",
            )
            if st.button("🎯 Submit Answer", type="primary"):
                if choice is None:
                    st.warning("Pick an option.")
                else:
                    correct = choice == q["correct_option"]
                    transition = record_correct() if correct else record_wrong()
                    s.quiz_result = {
                        "correct": correct,
                        "your_answer": f"{choice}. {q['options'][choice]}",
                        "correct_answer": f"{q['correct_option']}. {q['options'][q['correct_option']]}",
                        "explanation": q["explanation"],
                        "transition": transition,
                    }
                    st.rerun()
        return

    # Phase 2: feedback.
    r = s.quiz_result
    with st.container(border=True):
        if r["correct"]:
            st.success("✅ CORRECT!")
            st.balloons()
        else:
            st.error("❌ NOT QUITE")
            st.markdown(f"**Your answer:** {r['your_answer']}")
            st.markdown(f"**Correct answer:** {r['correct_answer']}")
        st.info(f"**Explanation:** {r['explanation']}")
        st.markdown(f"*{r['transition']}*")

    celebrate_levelups()

    if st.button("Continue →", type="primary"):
        s.study_content = None
        s.study_read = False
        s.quiz_question = None
        s.quiz_result = None
        s.phase = "STUDY"
        st.rerun()


