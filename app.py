def list_local_models():
    data = ollama.list()
    models = getattr(data, "models", None)
    if models is None and isinstance(data, dict):
        models = data.get("models", [])
    names = []
    for m in models or []:
        name = getattr(m, "model", None)
        if name is None and isinstance(m, dict):
            name = m.get("model") or m.get("name")
        if name:
            names.append(name)
    return names


def model_is_available(model, names):
    base = model.split(":")[0]
    return any(n == model or n.split(":")[0] == base for n in names)


def render_llm_error(exc):
    backend = st.session_state.backend
    if backend["name"] == "groq":
        st.error("**Couldn't reach the Groq API.** Check `GROQ_API_KEY` is set and the "
                 f"model `{backend['model']}` is valid / has quota.\n\nDetails: `{exc}`")
    else:
        st.error("**Couldn't reach the local model.**\n\n1. `ollama serve`\n"
                 f"2. `ollama pull {backend['model']}`\n\nDetails: `{exc}`")


