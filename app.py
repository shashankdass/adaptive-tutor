def _config(key, default=None):
    try:
        if key in st.secrets:
            return st.secrets[key]
    except Exception:  # noqa: BLE001
        pass
    return os.environ.get(key, default)


def resolve_backend():
    api_key = _config("GROQ_API_KEY")
    forced = (_config("LLM_BACKEND") or "").strip().lower()
    use_groq = forced == "groq" or (forced != "ollama" and bool(api_key))
    if use_groq:
        return {"name": "groq", "model": _config("LLM_MODEL", GROQ_MODEL), "api_key": api_key}
    return {"name": "ollama", "model": _config("LLM_MODEL", OLLAMA_MODEL), "api_key": None}


def _ollama_call(messages, temperature, json_mode):
    if ollama is None:
        raise RuntimeError("The 'ollama' package is not installed.")
    kwargs = {"model": st.session_state.backend["model"], "messages": messages,
              "options": {"temperature": temperature}}
    if json_mode:
        kwargs["format"] = "json"
    return ollama.chat(**kwargs)["message"]["content"]


def _groq_call(messages, temperature, json_mode):
    from openai import OpenAI

    client = OpenAI(api_key=st.session_state.backend["api_key"], base_url=GROQ_BASE_URL)
    kwargs = {"model": st.session_state.backend["model"], "messages": messages,
              "temperature": temperature}
    if json_mode:
        kwargs["response_format"] = {"type": "json_object"}
    return client.chat.completions.create(**kwargs).choices[0].message.content


def _chat(system_prompt, user_prompt, temperature=0.6, json_mode=False, retries=2):
    call = _groq_call if st.session_state.backend["name"] == "groq" else _ollama_call
    messages = [{"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}]
    last_err = None
    for _ in range(retries + 1):
        content = call(messages, temperature, json_mode)
        if not json_mode:
            return content
        try:
            return json.loads(content)
        except (json.JSONDecodeError, TypeError) as exc:
            last_err = exc
    raise ValueError(f"Model did not return valid JSON after retries: {last_err}")


def _generate_mcq_once(subject, chapter, difficulty):
    desc = SUBJECTS[subject][chapter][difficulty]
    system_prompt = (
        "You are an expert instructor writing one high-quality multiple-choice "
        "question. The option named by correct_option MUST be factually correct, "
        "and the explanation MUST justify that exact option (no contradictions). "
        "Respond ONLY with JSON — no markdown fences or extra prose."
    )
    user_prompt = f"""Create one {difficulty}-level multiple-choice question for "{chapter}" in a "{subject}" course.
Focus: {desc}

Return JSON EXACTLY like:
{{"question": "...", "options": {{"A": "...", "B": "...", "C": "...", "D": "..."}}, "correct_option": "A", "explanation": "why the correct answer is right"}}
correct_option MUST be one of A, B, C, D, and its option text must be the truly correct answer."""
    data = _chat(system_prompt, user_prompt, temperature=0.7, json_mode=True)
    if not all(k in data for k in ("question", "options", "correct_option", "explanation")):
        raise ValueError(f"Question JSON missing keys: {list(data)}")
    if not isinstance(data["options"], dict) or set(data["options"]) < set("ABCD"):
        raise ValueError("Options must include keys A, B, C, D.")
    if data["correct_option"] not in data["options"]:
        raise ValueError("correct_option does not match an option.")
    return data


def _verify_correct_option(q):
    opts = "\n".join(f"{k}. {v}" for k, v in q["options"].items())
    system_prompt = ("You are a meticulous exam grader. Decide which single option "
                     "is correct. Respond ONLY with JSON.")
    user_prompt = (f"Question: {q['question']}\nOptions:\n{opts}\n\n"
                   'Return {"correct_option": "X"} where X is the letter (A-D).')
    try:
        v = _chat(system_prompt, user_prompt, temperature=0.0, json_mode=True)
        letter = str(v.get("correct_option", "")).strip().upper()[:1]
        return letter if letter in q["options"] else None
    except Exception:  # noqa: BLE001
        return None


def generate_mcq(subject, chapter, difficulty, attempts=2):
    """Generate a self-consistent MCQ, verified by an independent LLM grader."""
    last = None
    for _ in range(attempts):
        q = _generate_mcq_once(subject, chapter, difficulty)
        last = q
        verdict = _verify_correct_option(q)
        if verdict is None or verdict == q["correct_option"]:
            return q
    verdict = _verify_correct_option(last)
    if verdict and verdict in last["options"]:
        last["correct_option"] = verdict
    return last


def generate_study_material(subject, chapter, difficulty):
    desc = SUBJECTS[subject][chapter][difficulty]
    system_prompt = (
        "You are an engaging tutor writing concise study notes in GitHub-flavored "
        "Markdown. Use a short intro, 3-5 bullet points, and a fenced code block or "
        "worked example where useful. Keep it under ~220 words. No preamble."
    )
    user_prompt = (f'Write {difficulty}-level study material for "{chapter}" in '
                   f'"{subject}". Focus on: {desc}. End with one quick takeaway.')
    return _chat(system_prompt, user_prompt, temperature=0.5, json_mode=False)


def generate_recovery_recommendation(label, accuracy):
    """One-sentence AI recovery tip for a flagged skill gap (templated fallback)."""
    try:
        system_prompt = ("You are a learning coach. In ONE short sentence, suggest a "
                         "concrete recovery step for a struggling student. No preamble.")
        user_prompt = (f'The student is at {int(accuracy * 100)}% accuracy on "{label}". '
                       "Recommend one specific recovery action.")
        return _chat(system_prompt, user_prompt, temperature=0.5, json_mode=False).strip()
    except Exception:  # noqa: BLE001
        return (f"Revisit the {label} fundamentals with a short guided review, then "
                "retry a Novice-tier quiz to rebuild confidence.")


def generate_tryit_brief(subject, chapter):
    """Short Markdown 'Try-It' brief explaining the module's pedagogy (fallback)."""
