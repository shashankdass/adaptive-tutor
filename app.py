def _finalize_diagnostic():
    correct = st.session_state.diag_correct
    baseline = "Novice" if correct <= 1 else "Intermediate" if correct == 2 else "Expert"
    st.session_state.baseline_skill = baseline
    st.session_state.current_difficulty = baseline
    st.session_state.phase = "STUDY"
    st.session_state.study_content = None
    st.session_state.study_read = False
    check_badges()


def phase_diagnostic():
    s = st.session_state
    st.title("🧪 DIAGNOSTIC SCAN")
    st.caption(f"{s.selected_subject} · calibrating your starting tier")
    if s.diag_index >= NUM_DIAGNOSTIC:
        _finalize_diagnostic()
        st.rerun()
        return
    probe_tier = TIERS[s.diag_index]
    if s.diag_question is None:
        with st.spinner(f"Generating probe {s.diag_index + 1}/{NUM_DIAGNOSTIC}…"):
            try:
                s.diag_question = generate_mcq(s.selected_subject, s.current_chapter, probe_tier)
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return
    q = s.diag_question
    st.progress(s.diag_index / NUM_DIAGNOSTIC, text=f"Probe {s.diag_index + 1} of {NUM_DIAGNOSTIC}")
    with st.container(border=True):
        st.markdown(f"**[{probe_tier}]** {q['question']}")
        choice = st.radio("Your answer:", list("ABCD"),
                          format_func=lambda k: f"{k}.  {q['options'][k]}",
                          index=None, key=f"diag_{s.diag_index}")
        if st.button("Submit ▶", type="primary"):
            if choice is None:
                st.warning("Pick an option.")
            else:
                if choice == q["correct_option"]:
                    s.diag_correct += 1
                s.diag_index += 1
                s.diag_question = None
                st.rerun()


def phase_study():
    s = st.session_state
    if s.completed:
        return phase_complete()
    st.title("📖 STUDY MODE")
    st.caption(f"{s.selected_subject} · {s.current_chapter} · **{s.current_difficulty}**")
    if s.baseline_skill:
        st.markdown(f"Diagnostic locked your baseline at **{s.baseline_skill}**. 🧠")
    if s.study_content is None:
        with st.spinner("Compiling your custom briefing…"):
            try:
                s.study_content = generate_study_material(
                    s.selected_subject, s.current_chapter, s.current_difficulty)
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return
    with st.container(border=True):
        st.markdown(s.study_content)
    col1, col2 = st.columns(2)
    with col1:
        if not s.study_read:
            if st.button(f"📗 Read Material (+{XP_READ} XP)", type="primary",
                         use_container_width=True):
                add_xp(XP_READ)
                s.study_read = True
                st.rerun()
        else:
            st.success(f"✓ +{XP_READ} XP claimed")
    with col2:
        if s.study_read and st.button("⚔️ Take the Quiz →", type="primary",
                                      use_container_width=True):
            s.phase = "QUIZ"
            s.quiz_question = None
            s.quiz_result = None
            st.rerun()
    celebrate_levelups()


def phase_quiz():
    s = st.session_state
    if s.completed:
        return phase_complete()
    st.title("⚔️ QUIZ ARENA")
    st.caption(f"{s.selected_subject} · {s.current_chapter} · **{s.current_difficulty}**")
    if s.quiz_question is None:
        with st.spinner("Summoning a challenge…"):
            try:
                s.quiz_question = generate_mcq(
                    s.selected_subject, s.current_chapter, s.current_difficulty)
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return
    q = s.quiz_question
    if s.quiz_result is None:
        with st.container(border=True):
            st.markdown(f"### {q['question']}")
            choice = st.radio("Lock in your answer:", list("ABCD"),
                              format_func=lambda k: f"{k}.  {q['options'][k]}",
                              index=None, key="quiz_choice")
            if st.button("🎯 Submit Answer", type="primary"):
                if choice is None:
                    st.warning("Pick an option.")
                else:
                    correct = choice == q["correct_option"]
                    transition = record_correct() if correct else record_wrong()
                    s.quiz_result = {
                        "correct": correct,
                        "your_answer": f"{choice}. {q['options'][choice]}",
                        "correct_answer": f"{q['correct_option']}. {q['options'][q['correct_option']]}",
                        "explanation": q["explanation"],
                        "transition": transition,
                    }
                    st.rerun()
        return
    r = s.quiz_result
    with st.container(border=True):
        if r["correct"]:
            st.success("✅ CORRECT!")
            st.balloons()
        else:
            st.error("❌ NOT QUITE")
            st.markdown(f"**Your answer:** {r['your_answer']}")
            st.markdown(f"**Correct answer:** {r['correct_answer']}")
        st.info(f"**Explanation:** {r['explanation']}")
        st.markdown(f"*{r['transition']}*")
    celebrate_levelups()
    if st.button("Continue →", type="primary"):
        s.study_content = None
        s.study_read = False
        s.quiz_question = None
        s.quiz_result = None
        s.phase = "STUDY"
        st.rerun()


def phase_complete():
    s = st.session_state
    st.balloons()
    st.title("🎓 SUBJECT MASTERED")
    with st.container(border=True):
        st.markdown(f"### You conquered **{s.selected_subject}**!")
        st.markdown(
            f"- **Level:** {s.level}\n- **Total XP:** {s.xp}\n"
            f"- **Badges:** {len(s.badges)}\n- **Chapters cleared:** {s.chapters_completed}"
        )
    if st.button("🕹️ Pick another subject", type="primary"):
        back_to_selection()
        st.rerun()


STUDENT_PHASES = {
    "SUBJECT_SELECTION": phase_subject_selection,
    "DIAGNOSTIC": phase_diagnostic,
    "STUDY": phase_study,
    "QUIZ": phase_quiz,
}


def render_student_arena():
    s = st.session_state
    # Subject selection is always open.
    if s.phase == "SUBJECT_SELECTION" or not s.selected_subject:
        phase_subject_selection()
        return
    # Gatekeeper: the active chapter must be parent-approved.
    if module_key(s.selected_subject, s.current_chapter) not in s.parent_approved_modules:
        render_locked()
        return
    STUDENT_PHASES.get(s.phase, phase_subject_selection)()


