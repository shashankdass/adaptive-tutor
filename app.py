# Default model per backend.
OLLAMA_MODEL = "llama3"
GROQ_MODEL = "llama-3.1-8b-instant"
GROQ_BASE_URL = "https://api.groq.com/openai/v1"


def _config(key, default=None):
    """Read a config value from Streamlit secrets (cloud) or env (local)."""
    try:
        if key in st.secrets:
            return st.secrets[key]
    except Exception:  # noqa: BLE001 — no secrets file in local dev is fine
        pass
    return os.environ.get(key, default)


def resolve_backend():
    """Pick the LLM backend. Groq if an API key is present, else local Ollama.

    Returns a dict: {name: 'groq'|'ollama', model: str, api_key: str|None}.
    """
    api_key = _config("GROQ_API_KEY")
    forced = (_config("LLM_BACKEND") or "").strip().lower()
    use_groq = forced == "groq" or (forced != "ollama" and bool(api_key))
    if use_groq:
        return {"name": "groq", "model": _config("LLM_MODEL", GROQ_MODEL),
                "api_key": api_key}
    return {"name": "ollama", "model": _config("LLM_MODEL", OLLAMA_MODEL),
            "api_key": None}


def chapters_for(subject):
    """Ordered list of chapter names for a subject ([] if none/unknown)."""
    return list(SUBJECTS.get(subject, {}).keys())


# --------------------------------------------------------------------------- #
# Ollama integration
# --------------------------------------------------------------------------- #
def list_local_models():
    """Return the list of model names available locally (raises on no server)."""
    data = ollama.list()
    models = getattr(data, "models", None)
    if models is None and isinstance(data, dict):
        models = data.get("models", [])
    names = []
    for m in models or []:
        name = getattr(m, "model", None)
        if name is None and isinstance(m, dict):
            name = m.get("model") or m.get("name")
        if name:
            names.append(name)
    return names


def model_is_available(model, names):
    """True if `model` matches a locally pulled model (with or without a tag)."""
    base = model.split(":")[0]
    return any(n == model or n.split(":")[0] == base for n in names)


def _ollama_chat(backend, messages, temperature):
    if ollama is None:
        raise RuntimeError("The 'ollama' package is not installed.")
    resp = ollama.chat(
        model=backend["model"],
        messages=messages,
        format="json",
        options={"temperature": temperature},
    )
    return resp["message"]["content"]


def _groq_chat(backend, messages, temperature):
    # Groq is OpenAI-compatible, so we reuse the openai client with its base URL.
    from openai import OpenAI

    client = OpenAI(api_key=backend["api_key"], base_url=GROQ_BASE_URL)
    resp = client.chat.completions.create(
        model=backend["model"],
        messages=messages,
        temperature=temperature,
        response_format={"type": "json_object"},
    )
    return resp.choices[0].message.content


def _chat_json(system_prompt, user_prompt, temperature=0.6, retries=2):
    """Call the active backend in JSON mode and return the parsed dict.

    Retries a few times if the model emits invalid JSON.
    """
    backend = st.session_state.backend
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]
    call = _groq_chat if backend["name"] == "groq" else _ollama_chat
    last_err = None
    for _ in range(retries + 1):
        content = call(backend, messages, temperature)
        try:
            return json.loads(content)
        except (json.JSONDecodeError, TypeError) as exc:
            last_err = exc
    raise ValueError(f"Model did not return valid JSON after retries: {last_err}")


def generate_adaptive_question(subject, chapter, difficulty):
    """Generate a multiple-choice question tuned to subject, chapter, and tier.

    Returns a dict: {question, options{A..D}, correct_option, explanation}.
    """
    tier_desc = SUBJECTS[subject][chapter][difficulty]
    system_prompt = (
        "You are an expert instructor writing a single high-quality "
        "multiple-choice question. Respond ONLY with JSON. Do not include "
        "markdown fences or any prose outside the JSON object."
    )
    user_prompt = f"""Create one {difficulty}-level multiple-choice question for the topic "{chapter}" in a "{subject}" course.

Difficulty guidance: {tier_desc}

Requirements:
- Exactly four answer options labelled A, B, C, D.
- Exactly one correct option.
- A concise explanation of why the correct answer is right.

Return JSON with EXACTLY this shape:
{{"question": "the question text", "options": {{"A": "...", "B": "...", "C": "...", "D": "..."}}, "correct_option": "A", "explanation": "why the correct answer is correct"}}

The value of correct_option MUST be one of: A, B, C, D."""

    data = _chat_json(system_prompt, user_prompt, temperature=0.7)

    required = ("question", "options", "correct_option", "explanation")
    if not all(k in data for k in required):
        raise ValueError(f"Question JSON missing keys. Got: {list(data)}")
    if not isinstance(data["options"], dict) or set(data["options"]) < set("ABCD"):
        raise ValueError("Question options must include keys A, B, C, D.")
    if data["correct_option"] not in data["options"]:
        raise ValueError("correct_option does not match any provided option.")
    return data


def evaluate_open_response(question, student_answer):
    """Grade a free-text answer with the model.

    Returns a dict: {is_correct: bool, confidence: int(0-100), feedback: str}.
    """
    system_prompt = (
        "You are a fair, encouraging tutor grading a student's free-text "
        "answer. Be rigorous about correctness but supportive in tone. Respond "
        "ONLY with JSON, no markdown fences or extra prose."
    )
    user_prompt = f"""Question: {question}

Student's answer: {student_answer}

Evaluate whether the student's answer is correct. Provide constructive feedback
that explains the correct reasoning regardless of whether they were right.

Return JSON with EXACTLY this shape:
{{"is_correct": true, "confidence": 85, "feedback": "constructive feedback and the correct explanation"}}

- is_correct: boolean.
- confidence: integer 0-100, your confidence in this evaluation.
- feedback: 1-3 sentences."""

    data = _chat_json(system_prompt, user_prompt, temperature=0.2)
    return {
        "is_correct": bool(data.get("is_correct", False)),
        "confidence": int(data.get("confidence", 0)),
        "feedback": str(data.get("feedback", "No feedback returned.")),
    }


