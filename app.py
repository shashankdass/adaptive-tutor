def ensure_backend_ready():
    backend = st.session_state.backend
    if backend["name"] == "groq":
        if not backend["api_key"]:
            st.error("**No `GROQ_API_KEY` configured.** Add it to Streamlit secrets or env.")
            return False
        return True
    try:
        names = list_local_models()
    except Exception as exc:  # noqa: BLE001
        render_llm_error(exc)
        if st.button("Retry connection"):
            st.rerun()
        return False
    if not model_is_available(backend["model"], names):
        st.warning(f"Model **{backend['model']}** isn't pulled. Run "
                   f"`ollama pull {backend['model']}` (have: {', '.join(names) or 'none'}).")
        if st.button("Retry"):
            st.rerun()
        return False
    return True


