def add_xp(amount):
    stats = st.session_state.student_stats
    stats["xp"] += amount
    new_level = 1 + stats["xp"] // XP_PER_LEVEL
    if new_level > stats["level"]:
        stats["level"] = new_level
        st.session_state.just_leveled = True


def check_badges():
    s = st.session_state
    stats = s.student_stats
    rules = [
        ("🎯 First Steps", stats["xp"] > 0),
        ("🔥 On Fire", stats["streak"] >= 3),
        ("⚡ Unstoppable", stats["streak"] >= 5),
        ("🌟 Rising Star", stats["level"] >= 2),
        ("👑 Scholar", stats["level"] >= 5),
        ("🧠 Prodigy", s.baseline_skill == "Expert"),
        ("📘 Module Master", len(s.completed_modules) >= 1),
    ]
    newly = []
    for title, cond in rules:
        if cond and title not in s.badges:
            s.badges.append(title)
            newly.append(title)
    return newly


def _record_accuracy(correct):
    key = module_key(st.session_state.current_subject, st.session_state.current_chapter)
    bucket = st.session_state.skill_gaps.setdefault(key, {"correct": 0, "total": 0})
    bucket["total"] += 1
    if correct:
        bucket["correct"] += 1


def _advance_or_complete():
    s = st.session_state
    idx = TIERS.index(s.current_difficulty)
    if idx < len(TIERS) - 1:
        s.current_difficulty = TIERS[idx + 1]
        return f"🎉 Promoted to **{s.current_difficulty}** tier!"
    key = module_key(s.current_subject, s.current_chapter)
    if key not in s.completed_modules:
        s.completed_modules.append(key)
    s.module_complete = True
    return "🏆 Module mastered — sequence complete!"


def _demote():
    s = st.session_state
    idx = TIERS.index(s.current_difficulty)
    if idx > 0:
        s.current_difficulty = TIERS[idx - 1]
        return f"↩️ Difficulty eased to **{s.current_difficulty}** — reinforce the basics."
    return "💪 Holding at Novice — let's build a solid base."


def record_correct():
    s = st.session_state
    _record_accuracy(True)
    add_xp(XP_CORRECT)
    s.student_stats["streak"] += 1
    s.consecutive_correct += 1
    if s.consecutive_correct >= PROMOTION_THRESHOLD:
        s.consecutive_correct = 0
        return _advance_or_complete()
    remaining = PROMOTION_THRESHOLD - s.consecutive_correct
    return f"✅ Correct! +{XP_CORRECT} XP · {remaining} more to advance."


def record_wrong():
    s = st.session_state
    _record_accuracy(False)
    s.student_stats["streak"] = 0
    s.consecutive_correct = 0
    return _demote()


def flagged_gaps():
    """List of (module_key, accuracy) below threshold with enough attempts."""
    out = []
    for key, v in st.session_state.skill_gaps.items():
        if v["total"] >= GAP_MIN_ATTEMPTS:
            acc = v["correct"] / v["total"]
            if acc < GAP_THRESHOLD:
                out.append((key, acc))
    return out


def build_digest_payload():
    s = st.session_state
    stats = s.student_stats
    return {
        "type": "weekly_progress_digest",
        "to": "parent@example.com",
        "student": {"avatar": stats["avatar"], "level": stats["level"],
                    "xp": stats["xp"], "streak": stats["streak"]},
        "active_goals": s.selected_goals,
        "modules_completed": len(s.completed_modules),
        "skill_gaps": [
            {"topic": k.split(" :: ")[-1], "accuracy": round(v["correct"] / v["total"], 2)}
            for k, v in s.skill_gaps.items()
            if v["total"] >= GAP_MIN_ATTEMPTS and v["correct"] / v["total"] < GAP_THRESHOLD
        ],
        "next_send": "Mon 09:00 (simulated)",
    }


