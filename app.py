# Phase: DIAGNOSTIC
# =========================================================================== #
def _finalize_diagnostic():
    correct = st.session_state.diag_correct
    baseline = "Novice" if correct <= 1 else "Intermediate" if correct == 2 else "Expert"
    st.session_state.baseline_skill = baseline
    st.session_state.current_difficulty = baseline
    st.session_state.phase = "STUDY"
    st.session_state.study_content = None
    st.session_state.study_read = False
    check_badges()  # 🧠 Prodigy if Expert


def phase_diagnostic():
    s = st.session_state
    st.title("🧪 DIAGNOSTIC SCAN")
    st.caption(f"{s.selected_subject} · calibrating your starting tier")

    if s.diag_index >= NUM_DIAGNOSTIC:
        _finalize_diagnostic()
        st.rerun()
        return

    # One probe per tier: Novice → Intermediate → Expert.
    probe_tier = TIERS[s.diag_index]
    if s.diag_question is None:
        with st.spinner(f"Generating probe {s.diag_index + 1}/{NUM_DIAGNOSTIC}…"):
            try:
                s.diag_question = generate_mcq(
                    s.selected_subject, s.current_chapter, probe_tier
                )
            except Exception as exc:  # noqa: BLE001
                render_llm_error(exc)
                if st.button("Try again"):
                    st.rerun()
                return

    q = s.diag_question
    st.progress(s.diag_index / NUM_DIAGNOSTIC, text=f"Probe {s.diag_index + 1} of {NUM_DIAGNOSTIC}")
    with st.container(border=True):
        st.markdown(f"**[{probe_tier}]** {q['question']}")
        choice = st.radio(
            "Your answer:", list("ABCD"),
            format_func=lambda k: f"{k}.  {q['options'][k]}",
            index=None, key=f"diag_{s.diag_index}",
        )
        if st.button("Submit ▶", type="primary"):
            if choice is None:
                st.warning("Pick an option.")
            else:
                if choice == q["correct_option"]:
                    s.diag_correct += 1
                s.diag_index += 1
                s.diag_question = None
                st.rerun()


