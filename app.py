def render_student_arena():
    s = st.session_state
    if s.phase == "PATH" or not s.current_subject:
        phase_path()
        return
    path_keys = {module_key(sub, ch) for sub, ch in student_path()}
    if module_key(s.current_subject, s.current_chapter) not in path_keys:
        st.toast("That quest isn't on your map right now.")
        back_to_path()
        phase_path()
        return
    if not ensure_backend_ready():
        return
    STUDENT_PHASES.get(s.phase, phase_path)()


