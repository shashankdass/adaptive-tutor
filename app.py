def parse_custom_parental_goal(text):
    """Map a free-text parent goal to catalog module keys using the LLM.

    Returns a list of module keys (possibly empty if nothing matched / errored).
    """
    name_to_key, catalog_lines = {}, []
    for track, mods in SUBJECTS.items():
        for mod in mods:
            name_to_key[mod] = module_key(track, mod)
            catalog_lines.append(f"- {mod} [{band_for(track)}]: {SUBJECTS[track][mod]['Novice']}")
    catalog = "\n".join(catalog_lines)
    system_prompt = (
        "You are a K-12 learning planner. From the FIXED module catalog, choose the "
        "2-4 modules that best match the parent's goal or the child's interest. Use "
        "ONLY exact module names from the catalog. Respond ONLY with JSON."
    )
    user_prompt = (f'Parent goal / interest: "{text}"\n\nModule catalog:\n{catalog}\n\n'
                   'Return {"modules": ["Exact Module Name", ...]} with 2-4 names from the catalog.')
    try:
        data = _chat(system_prompt, user_prompt, temperature=0.2, json_mode=True)
        picked = [m for m in data.get("modules", []) if m in name_to_key]
        return [name_to_key[m] for m in dict.fromkeys(picked)]  # dedup, keep order
    except Exception:  # noqa: BLE001
        return []


def list_local_models():
    data = ollama.list()
    models = getattr(data, "models", None)
    if models is None and isinstance(data, dict):
        models = data.get("models", [])
    names = []
    for m in models or []:
        name = getattr(m, "model", None)
        if name is None and isinstance(m, dict):
            name = m.get("model") or m.get("name")
        if name:
            names.append(name)
    return names


def model_is_available(model, names):
    base = model.split(":")[0]
    return any(n == model or n.split(":")[0] == base for n in names)


