def module_key(subject, chapter):
    return f"{subject} :: {chapter}"


def student_path():
    """Ordered, de-duplicated (subject, chapter) modules from selected goals."""
    seen, path = set(), []
    for goal in st.session_state.selected_goals:
        for subject, chapter in GOALS.get(goal, {}).get("modules", []):
            key = module_key(subject, chapter)
            if key not in seen:
                seen.add(key)
                path.append((subject, chapter))
    return path


