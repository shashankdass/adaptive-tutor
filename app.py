def student_path():
    """Ordered, de-duplicated (track, module) list from parent-approved modules."""
    seen, path = set(), []
    for key in st.session_state.parent_approved_modules:
        if " :: " not in key:
            continue
        track, mod = key.split(" :: ", 1)
        if track in SUBJECTS and mod in SUBJECTS[track] and key not in seen:
            seen.add(key)
            path.append((track, mod))
    return path


