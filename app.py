    cols = st.columns(2)
    for i, (subject, chapter) in enumerate(path):
        key = module_key(subject, chapter)
        done = key in s.completed_modules
        status = "✅ Completed" if done else "▶ Ready"
        with cols[i % 2]:
            st.markdown(
                f'<div class="mission-card"><div class="title">{chapter}</div>'
                f'<div class="blurb">{subject} · {status}</div></div>',
                unsafe_allow_html=True,
            )
